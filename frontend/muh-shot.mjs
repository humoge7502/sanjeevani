import { chromium } from "playwright";
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
await page.goto("http://127.0.0.1:5175/");
await page.waitForSelector("article", { timeout: 20000 });
const skip = page.getByText("Skip", { exact: false }).first();
if (await skip.isVisible().catch(() => false)) await skip.click();
await page.waitForTimeout(1200);
await page.screenshot({ path: "C:/Users/Devesh tiwari/OneDrive/Documents/Trae/default/muhurat/docs/assets/app-dashboard.png" });
await page.getByRole("button", { name: "Tour" }).click();
await page.waitForTimeout(900);
await page.screenshot({ path: "C:/Users/Devesh tiwari/OneDrive/Documents/Trae/default/muhurat/docs/assets/app-tour.png" });
const done = page.getByText("Skip", { exact: false }).first();
if (await done.isVisible().catch(() => false)) await done.click();
await page.waitForTimeout(400);
const cards = await page.locator("article").count();
const bodyText = await page.locator("body").innerText();
console.log(JSON.stringify({ cards, hasMuhurat: bodyText.includes("Muhurat"), hasCountdown: /left/.test(bodyText), hasSources: bodyText.includes("codeforces") && bodyText.includes("devpost") && bodyText.includes("opportunitydesk") }));
await browser.close();
