#!/usr/bin/env python3
"""Generate or update the identity file that the auth layer reads.

    python scripts/make_identity.py --demo              # write the demo roster
    python scripts/make_identity.py --account "id:password:role:tenant:Full Name:Title"

WHY A SCRIPT. A password hash must never be typed by hand, and a plaintext
password must never be committed. This is the only place plaintext exists, and it
exists in memory for the length of one command.

The ``--demo`` roster uses the credentials documented in
``docs/security-threat-model.md``. They are **demo credentials for a prototype**:
they are published on purpose so a reviewer can sign in, and they must be replaced
before any deployment that faces a network.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from backend.security.identity import KNOWN_ROLES, hash_password

#: id, password, role, tenant, full_name, title
DEMO_ACCOUNTS: list[tuple[str, str, str, str, str, str]] = [
    ("meera.iyer", "demo-meera-2026", "supply_planning_head", "acme-pharma",
     "Meera Iyer", "Head of Supply Planning"),
    ("rajan.kulkarni", "demo-rajan-2026", "coo", "acme-pharma",
     "Rajan Kulkarni", "Chief Operating Officer"),
    ("anil.deshpande", "demo-anil-2026", "planner", "acme-pharma",
     "Anil Deshpande", "Senior Supply Planner"),
    ("svc.admin", "demo-admin-2026", "admin", "acme-pharma",
     "Platform Administrator", "Platform owner"),
    ("user.auditor", "demo-auditor-2026", "auditor", "acme-pharma",
     "Compliance Auditor", "Read-only compliance reviewer"),
    ("user.viewer", "demo-viewer-2026", "viewer", "acme-pharma",
     "Planning Viewer", "Read-only planner"),
    ("meera.novartis", "demo-helix-2026", "supply_planning_head", "helix-biologics",
     "Meera Nair", "Head of Supply Planning (second tenant)"),
]

HEADER = """\
# SANJEEVANI identity file -- accounts, roles and tenants.
#
# Consumed by backend/security/identity.py when SANJEEVANI_AUTH_ENABLED=true.
# It is IGNORED when authentication is off, which is the default.
#
#   password_hash format: pbkdf2_sha256$<iterations>$<salt>$<digest>
#   Generated by:         python scripts/make_identity.py
#
# ⚠️  The accounts below are DEMO CREDENTIALS for a hackfest prototype. Their
#     passwords are documented in docs/security-threat-model.md on purpose, so a
#     reviewer can sign in. Replace every one of them, and rotate
#     SANJEEVANI_JWT_SECRET, before any deployment reachable from a network.
#
# Roles are exact-match (see backend/governance/approval.py:role_satisfies):
# a 'coo' does NOT implicitly satisfy a 'planner' requirement.
#
# Tenants are a claim in the verified token, never a request parameter. Data
# carrying a different tenant is invisible to this principal.

meta:
  identity_version: "1.0.0"
  default_tenant: "acme-pharma"
  #: PBKDF2-HMAC-SHA256 iterations used for newly generated hashes. Verification
  #: reads the count stored in each hash, so raising this needs no migration.
  pbkdf2_iterations: 210000

accounts:
"""


def _render(account_row: tuple[str, str, str, str, str, str]) -> str:
    account_id, password, role, tenant, full_name, title = account_row
    digest = hash_password(password, iterations=210_000)
    return (
        f"  - id: {account_id}\n"
        f"    name: {full_name.split()[0]}\n"
        f"    full_name: {full_name}\n"
        f"    role: {role}\n"
        f"    tenant: {tenant}\n"
        f'    title: "{title}"\n'
        f'    password_hash: "{digest}"\n'
    )


def _parse_account(spec: str) -> tuple[str, str, str, str, str, str]:
    parts = spec.split(":", 5)
    if len(parts) < 4:
        raise SystemExit(
            "An --account must be 'id:password:role:tenant[:Full Name[:Title]]'. "
            f"Got {spec!r}."
        )
    account_id, password, role, tenant = parts[:4]
    if role not in KNOWN_ROLES:
        raise SystemExit(f"Unknown role {role!r}. Known roles: {sorted(KNOWN_ROLES)}")
    full_name = parts[4] if len(parts) > 4 and parts[4] else account_id
    title = parts[5] if len(parts) > 5 and parts[5] else role
    return (account_id, password, role, tenant, full_name, title)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--demo", action="store_true", help="write the documented demo roster")
    parser.add_argument(
        "--account",
        action="append",
        default=[],
        metavar="id:password:role:tenant[:Full Name[:Title]]",
        help="add or replace one account",
    )
    parser.add_argument(
        "--out",
        default=str(REPO_ROOT / "config" / "identity.yaml"),
        help="destination file (default: config/identity.yaml)",
    )
    args = parser.parse_args()

    if not args.demo and not args.account:
        parser.error("nothing to do: pass --demo and/or at least one --account")

    rows = list(DEMO_ACCOUNTS) if args.demo else []
    rows.extend(_parse_account(spec) for spec in args.account)

    seen: set[str] = set()
    ordered: list[tuple[str, str, str, str, str, str]] = []
    for row in reversed(rows):
        if row[0] in seen:
            continue
        seen.add(row[0])
        ordered.append(row)
    ordered.reverse()

    Path(args.out).write_text(HEADER + "".join(_render(r) for r in ordered), encoding="utf-8")
    print(f"wrote {len(ordered)} account(s) to {args.out}")
    for row in ordered:
        print(f"  {row[0]:<18} role={row[2]:<22} tenant={row[3]}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
